// Self-host the Google Fonts the site actually uses.
//
// next/font/google would normally do this, but it emitted zero @font-face
// rules and zero font files in this environment on both Turbopack and webpack.
// Doing it explicitly removes the build-time network dependency entirely and
// makes the result auditable: the woff2 files are in the repo.
//
// Only latin + latin-ext subsets are kept. The Google CSS ships 67 @font-face
// blocks covering Cyrillic, Greek and Vietnamese, none of which this site uses.
const fs = require('fs');
const path = require('path');
const https = require('https');

const CSS = fs.readFileSync(process.argv[2], 'utf8');
const OUT_DIR = process.argv[3];
const CSS_OUT = process.argv[4];

const KEEP = new Set(['latin', 'latin-ext']);

function get(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode !== 200) return reject(new Error(`${res.statusCode} for ${url}`));
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
    }).on('error', reject);
  });
}

// Split into "/* subset */ @font-face { ... }" pairs.
const blocks = [...CSS.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];

(async () => {
  const kept = [];
  const seen = new Map();

  for (const [, subset, block] of blocks) {
    if (!KEEP.has(subset)) continue;

    const family = /font-family:\s*'([^']+)'/.exec(block)[1];
    const weight = /font-weight:\s*(\d+)/.exec(block)[1];
    const style = /font-style:\s*(\w+)/.exec(block)[1];
    const url = /url\(([^)]+)\)/.exec(block)[1];

    const slug = family.toLowerCase().replace(/\s+/g, '-');
    const file = `${slug}-${weight}${style === 'italic' ? '-italic' : ''}-${subset}.woff2`;
    const dest = path.join(OUT_DIR, file);

    if (!seen.has(url)) {
      const buf = await get(url);
      fs.writeFileSync(dest, buf);
      seen.set(url, buf.length);
      process.stdout.write(`  ${file.padEnd(46)} ${(buf.length / 1024).toFixed(1)} KB\n`);
    }

    kept.push(
      block
        .replace(/url\([^)]+\)/, `url('/fonts/${file}')`)
        // Keep the browser from blocking first paint on a font it hasn't got yet.
        .replace(/font-display:\s*\w+/, 'font-display: swap')
    );
  }

  const header = `/* Self-hosted fonts. Generated by scripts/self-host-fonts.sh — do not edit by hand.
   Only latin and latin-ext subsets are included; the site is English-only.
   Serving these from our own origin removes two DNS lookups, a TLS handshake
   and a render-blocking stylesheet from fonts.googleapis.com. */\n\n`;

  fs.writeFileSync(CSS_OUT, header + kept.join('\n\n') + '\n');
  const total = [...seen.values()].reduce((a, b) => a + b, 0);
  console.log(`\n  ${seen.size} font files, ${(total / 1024).toFixed(0)} KB total`);
  console.log(`  ${kept.length} @font-face rules -> ${CSS_OUT}`);
})();
